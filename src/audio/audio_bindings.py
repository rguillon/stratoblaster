"""A game's music and sounds, as the engine takes them (P12-R05..R10), ported from
`audio/audio-bindings.ts`. The engine knows the moments (cues, see `level_cues.py`) and the music
wanted; the game decides how they sound.

`MusicRequest` is a TypeScript union: `kind` says which of `level_id` (level, boss) or `jingle`
(jingle) is set; the others are None.
"""

from org.transcrypt.stubs.browser import __pragma__

__pragma__("skip")
from typing import Literal  # noqa: E402

__pragma__("noskip")


__pragma__("skip")
from collections.abc import Callable  # noqa: E402

# The jingles a game plays once (P12-R07).
type Jingle = Literal["complete", "over", "checkpoint"]
__pragma__("noskip")

from audio.audio_types import Instrument, MusicEffects, SoundDesign, Track  # noqa: E402


class MusicRequest:
    """Which music is wanted: `menu`, `level`, `boss` (both with `level_id`), or `jingle`."""

    def __init__(self, kind: str, level_id: str | None, jingle: str | None) -> None:
        self.kind = kind
        self.level_id = level_id
        self.jingle = jingle


class AudioMix:
    """Levels of the music and sound effect buses at full volume."""

    def __init__(self, music: float, sfx: float) -> None:
        self.music = music
        self.sfx = sfx


class AudioBindings:
    """A game's music and sounds (`GameView.audio`, P12-R05..R10): all generated by code from
    data (see the module doc)."""

    def __init__(  # noqa: PLR0917 (positional: Transcrypt has no keyword arguments)
        self,
        music: Callable[[MusicRequest], Track | None],
        instruments: dict[str, Instrument],
        sounds: dict[str, SoundDesign],
        large_blast_radius: float,
        mix: AudioMix,
        effects: MusicEffects | None = None,
    ) -> None:
        # The track for a request, made once and kept; None: silence.
        self.music = music
        # The instruments the tracks' notes name.
        self.instruments = instruments
        # The sound of each cue (`SoundCue.cue`); cues without one are silent.
        self.sounds = sounds
        # Explosions at least this big (radius, logical pixels) play `blast-large`.
        self.large_blast_radius = large_blast_radius
        # Levels of the music and sound effect buses at full volume.
        self.mix = mix
        # The music's echo and reverb; dry when None.
        self.effects = effects
